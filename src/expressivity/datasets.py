"""Artificial data generation.

The synthetic dataset is generated in a manner similar to [1804.11326]. The data are
generated by creating a set of random points in [0, 2pi]^2. Then this set is fed into
a PQC of 2 qubits that rotates each qubit i by a set amount x_i in each direction,
followed by a random unitary U. The label comes from the expected value

    < C2 Z(x1, x2) C2 >

where C2 is a CNOT gate with qubit 2 as its target and Z(x1, x2) rotates by an angle
f(x1, x2) in the z-direction. The specific form of this function changes the shape of
the classification:

    dataset 1  f = x2       linearly separated dataset
    dataset 2  f = x1 - x2  two decision boundaries need be drawn
    dataset 3  f = x1 x2    even more complex wavy dataset

Points with an expected value between -0.3 and 0.3 get a random label. Afterwards
the dataset is balanced so that both classes are represented equally.

Note: C2 Rz(f) C2 = exp(-i f Z Z / 2), so the real part of the expected value is
cos(f/2) for any state. The boundaries are therefore where f(x1, x2) = (2k+1) pi.
"""

from dataclasses import dataclass, field

import numpy as np
from sklearn.model_selection import train_test_split

from .quantum_circuits import CNOT, apply_gate, random_unitary, rx, ry, rz, zero_state

ROTATION_FUNCTIONS = {
    "linear": lambda x1, x2: x2,
    "difference": lambda x1, x2: x1 - x2,
    "product": lambda x1, x2: x1 * x2,
}

DATASET_ALIASES = {"1": "linear", "2": "difference", "3": "product",
                   "dataset1": "linear", "dataset2": "difference", "dataset3": "product"}


def product_feature(X):
    """Third input x1 * x2, used to bias the classifier towards a specific shape."""
    return X[:, 0] * X[:, 1]


@dataclass
class Dataset:
    name: str
    X: np.ndarray            # points in [0, 2pi]^2
    y: np.ndarray            # labels 0 / 1
    expectation: np.ndarray  # expected value measured by the generator
    margin: float
    seed: int
    extra_feature: object = field(default=product_feature, repr=False)

    def __len__(self):
        return len(self.y)

    @property
    def features(self):
        """The 3 inputs of the classifiers: x1, x2 and a combination of x1 and x2."""
        return np.column_stack([self.X, self.extra_feature(self.X)])

    @property
    def class_balance(self):
        return float(np.mean(self.y))

    def split(self, test_size=0.5, seed=42):
        """X_train, X_test, y_train, y_test (stratified, 50/50 as in the report)."""
        return train_test_split(self.features, self.y, test_size=test_size,
                                random_state=seed, stratify=self.y)


def sample_points(n_points, rng=None):
    """Random points in [0, 2pi]^2."""
    return 2 * np.pi * np.random.default_rng(rng).random((n_points, 2))


def generator_expectation(X, rotation, unitary):
    """Expected value of C2 Z(f(x1, x2)) C2 for every point (real part)."""
    X = np.atleast_2d(X)
    state = zero_state(2, len(X))
    # rotate each qubit by x_i in all 3 directions, then apply U
    for gate in (rx, ry, rz):
        for q in range(2):
            state = apply_gate(state, gate(X[:, q]), [q])
    state = apply_gate(state, unitary, [0, 1])

    f = rotation(X[:, 0], X[:, 1])
    out = apply_gate(state, CNOT, [0, 1])
    out = apply_gate(out, rz(f), [1])
    out = apply_gate(out, CNOT, [0, 1])
    return np.real(np.sum(state.conj() * out, axis=1))


def assign_labels(expval, margin=0.3, rng=None):
    """1 if expval >= margin, 0 if expval <= -margin, random label in between."""
    if margin < 0:
        raise ValueError("margin must be non-negative")
    expval = np.asarray(expval)
    labels = (expval >= 0).astype(int)
    unsure = np.abs(expval) < margin
    labels[unsure] = np.random.default_rng(rng).integers(0, 2, size=unsure.sum())
    return labels


def make_dataset(name="linear", n_points=1000, margin=0.3, balance=True, seed=0,
                 extra_feature=product_feature):
    """Generate one of the 3 datasets ('linear'/1, 'difference'/2, 'product'/3)."""
    key = DATASET_ALIASES.get(str(name).lower(), str(name).lower())
    if key not in ROTATION_FUNCTIONS:
        raise ValueError(f"unknown dataset {name!r}, choose from {list(ROTATION_FUNCTIONS)}")
    if n_points < 2 or (balance and n_points % 2):
        raise ValueError("n_points must be at least 2 (and even when balance=True)")

    rng = np.random.default_rng(seed)
    rotation = ROTATION_FUNCTIONS[key]
    U = random_unitary(4, rng)  # drawn once per dataset

    def classifier(n):
        X = sample_points(n, rng)
        expval = generator_expectation(X, rotation, U)
        return X, expval, assign_labels(expval, margin, rng)

    if not balance:
        X, expval, y = classifier(n_points)
    else:
        # keep drawing points until both classes have n_points / 2 examples
        half = n_points // 2
        kept_X, kept_e = {0: [], 1: []}, {0: [], 1: []}
        while min(sum(len(a) for a in kept_X[c]) for c in (0, 1)) < half:
            Xb, eb, yb = classifier(max(n_points, 256))
            for c in (0, 1):
                missing = half - sum(len(a) for a in kept_X[c])
                idx = np.flatnonzero(yb == c)[:missing]
                kept_X[c].append(Xb[idx])
                kept_e[c].append(eb[idx])
        X = np.concatenate(kept_X[0] + kept_X[1])
        expval = np.concatenate(kept_e[0] + kept_e[1])
        y = np.repeat([0, 1], half)
        order = rng.permutation(n_points)
        X, expval, y = X[order], expval[order], y[order]

    return Dataset(key, X, y, expval, margin, seed, extra_feature)
